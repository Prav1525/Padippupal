"""Admin-only Gemini image generation for approved PadippuPal Science lesson steps.

Generated bytes are stored in the existing PostgreSQL BYTEA image store and mapped
to the exact lesson/teaching-step IDs. New assets remain pending_review until
a human checks the image; learner read endpoints expose only ready assets.
"""
from __future__ import annotations

import hashlib
import json
import os
import re
import urllib.error
import urllib.request
from typing import Any

from fastapi import APIRouter, Depends, HTTPException
from pydantic import BaseModel, Field

from lesson_image_ingest import connect, ensure_blob_table, require_image_admin

router = APIRouter(prefix="/admin/visuals", tags=["admin-visual-generation"])

MAX_STEPS_PER_REQUEST = 8
MAX_IMAGE_BYTES = 8 * 1024 * 1024
STEP_ID_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._:-]{0,120}$")
DEFAULT_IMAGE_MODEL = "gemini-3.1-flash-image"


class GenerateLessonImagesRequest(BaseModel):
    step_ids: list[str] | None = Field(default=None, max_length=MAX_STEPS_PER_REQUEST)
    overwrite: bool = False


def _png_dimensions(payload: bytes) -> tuple[int, int]:
    """Validate a PNG signature and IHDR dimensions without trusting file names."""
    if len(payload) < 24 or not payload.startswith(b"\x89PNG\r\n\x1a\n"):
        raise HTTPException(status_code=502, detail="Gemini returned data that is not a PNG image.")
    if payload[12:16] != b"IHDR":
        raise HTTPException(status_code=502, detail="Gemini returned an invalid PNG header.")
    width = int.from_bytes(payload[16:20], "big")
    height = int.from_bytes(payload[20:24], "big")
    if not (512 <= width <= 4096 and 512 <= height <= 4096):
        raise HTTPException(status_code=502, detail="Generated image dimensions are outside the accepted range.")
    if len(payload) > MAX_IMAGE_BYTES:
        raise HTTPException(status_code=413, detail="Generated image exceeds the 8 MB limit.")
    return width, height


def _step_prompt(lesson: dict[str, Any], step: dict[str, Any]) -> str:
    medium = str(lesson.get("medium") or "English").strip()
    language = {
        "tamil": "Use short, correctly spelled Tamil labels.",
        "tanglish": "Use short, correctly spelled Tamil words transliterated into Latin script for labels.",
    }.get(medium.casefold(), "Use short, correctly spelled English labels.")
    visual = step.get("visual", {})
    visual_text = json.dumps(visual, ensure_ascii=False, separators=(",", ":"))[:3500]
    title = str(step.get("title") or step.get("heading") or "").strip()[:240]
    caption = str(step.get("caption") or step.get("description") or "").strip()[:700]
    chapter = str(lesson.get("chapter") or "").strip()[:160]
    topic = str(lesson.get("topic") or "").strip()[:160]
    return f"""Create ONE original educational science illustration for a PadippuPal school tutor.
Learner: {lesson.get('board', 'school curriculum')} Class {lesson.get('class_level', '')}.
Chapter: {chapter}. Topic: {topic}. Teaching step: {title}.
Step explanation: {caption}
Visual specification from the approved lesson: {visual_text}

ART DIRECTION:
Excalidraw-inspired teacher's classroom-board drawing: confident hand-drawn pencil
outlines, coloured marker accents, subtle soft shading, clean warm-white background,
friendly and engaging for children, scientifically accurate objects and relationships.
Make the main concept large and immediately understandable. Use clear arrows and
leader lines that point to the correct objects. Keep the composition compact and
mobile-friendly in a portrait 3:4 layout. No SVG, no photo collage, no watermark,
no decorative border, no unrelated objects, no paragraphs, no filler text.

LABEL RULES:
{language}
Only include short labels directly supported by the step title, caption, or visual
specification above. Do not invent labels, numbers, facts, or measurements. Keep
labels large and separated from lines and objects. If a label cannot be rendered
exactly, leave it out rather than spelling it incorrectly.

The illustration must teach THIS step only, not the whole chapter. Return image only."""


def _generate_with_gemini(prompt: str) -> tuple[bytes, str]:
    api_key = os.getenv("GEMINI_API_KEY", "").strip()
    if not api_key:
        raise HTTPException(status_code=503, detail="Gemini image generation is not configured on the backend.")
    model = os.getenv("PADIPPUPAL_GEMINI_IMAGE_MODEL", DEFAULT_IMAGE_MODEL).strip()
    if not re.fullmatch(r"[A-Za-z0-9._-]{3,100}", model):
        raise HTTPException(status_code=503, detail="Gemini image model configuration is invalid.")
    body = json.dumps({
        "contents": [{"role": "user", "parts": [{"text": prompt}]}],
        "generationConfig": {
            "responseModalities": ["IMAGE"],
            "imageConfig": {"aspectRatio": "3:4"},
        },
    }).encode("utf-8")
    request = urllib.request.Request(
        f"https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent",
        data=body,
        headers={
            "x-goog-api-key": api_key,
            "Content-Type": "application/json",
            "Accept": "application/json",
        },
        method="POST",
    )
    try:
        with urllib.request.urlopen(request, timeout=150) as response:
            result = json.loads(response.read().decode("utf-8"))
        parts = result["candidates"][0]["content"]["parts"]
        image_parts = [
            part.get("inlineData") for part in parts
            if isinstance(part, dict) and isinstance(part.get("inlineData"), dict)
            and part["inlineData"].get("data")
        ]
        if not image_parts:
            raise ValueError("Gemini returned no image data")
        import base64
        payload = base64.b64decode(image_parts[0]["data"], validate=True)
        _png_dimensions(payload)
        return payload, model
    except urllib.error.HTTPError as exc:
        # Keep provider bodies and credentials out of API responses and logs.
        if exc.code == 429:
            raise HTTPException(status_code=503, detail="Gemini image generation quota is temporarily exhausted.") from exc
        raise HTTPException(status_code=502, detail=f"Gemini image generation failed (HTTP {exc.code}).") from exc
    except HTTPException:
        raise
    except (urllib.error.URLError, TimeoutError, KeyError, IndexError, TypeError,
            ValueError, json.JSONDecodeError) as exc:
        raise HTTPException(status_code=502, detail="Gemini did not return a valid image. No database write was made.") from exc


@router.post("/generate/{lesson_id}", dependencies=[Depends(require_image_admin)])
def generate_science_lesson_images(
    lesson_id: str,
    payload: GenerateLessonImagesRequest,
) -> dict[str, Any]:
    """Generate images for selected teaching steps of one approved Science lesson."""
    if not lesson_id or len(lesson_id) > 160:
        raise HTTPException(status_code=422, detail="Invalid lesson ID.")
    conn = connect()
    try:
        lesson_row = conn.execute(
            """SELECT id, board, class_level, subject, medium, chapter, topic,
                      status, lesson_json
               FROM chapter_lessons WHERE id=%s""",
            (lesson_id,),
        ).fetchone()
        if not lesson_row or lesson_row["status"] != "approved":
            raise HTTPException(status_code=404, detail="Approved lesson not found.")
        if str(lesson_row["subject"]).strip().casefold() != "science":
            raise HTTPException(status_code=422, detail="Image generation is currently limited to approved Science lessons.")
        lesson = dict(lesson_row)
        try:
            lesson_json = json.loads(lesson["lesson_json"] or "{}")
        except (TypeError, ValueError) as exc:
            raise HTTPException(status_code=422, detail="Approved lesson content is not valid JSON.") from exc
        steps = lesson_json.get("teaching_sequence")
        if not isinstance(steps, list) or not steps:
            raise HTTPException(status_code=422, detail="This lesson has no saved teaching_sequence to map images against.")
        if payload.step_ids is not None:
            requested = set(payload.step_ids)
            if len(requested) != len(payload.step_ids):
                raise HTTPException(status_code=422, detail="Duplicate step IDs are not allowed.")
            steps = [step for step in steps if isinstance(step, dict) and str(step.get("id", "")) in requested]
            if len(steps) != len(requested):
                raise HTTPException(status_code=422, detail="One or more requested step IDs do not belong to this lesson.")
        if len(steps) > MAX_STEPS_PER_REQUEST:
            raise HTTPException(status_code=413, detail=f"Generate at most {MAX_STEPS_PER_REQUEST} steps per request.")
        prepared = []
        for step in steps:
            step_id = str(step.get("id") or "").strip()
            title = str(step.get("title") or step.get("heading") or "").strip()
            caption = str(step.get("caption") or step.get("description") or "").strip()
            visual = step.get("visual")
            if not STEP_ID_RE.fullmatch(step_id) or not title or (not caption and not visual):
                raise HTTPException(status_code=422, detail="Every image needs a valid step ID and grounded teaching content.")
            prompt = _step_prompt(lesson, step)
            fingerprint = hashlib.sha256((DEFAULT_IMAGE_MODEL + "\n" + prompt).encode("utf-8")).hexdigest()
            prepared.append((step_id, title, prompt, fingerprint))
    finally:
        conn.close()

    # Generate before opening the write transaction. A provider failure cannot leave
    # partially registered assets, and database locks are not held during generation.
    generated = []
    actual_model = ""
    for step_id, title, prompt, fingerprint in prepared:
        asset_id = "gemini-" + hashlib.sha256(f"{lesson_id}:{step_id}".encode("utf-8")).hexdigest()[:40]
        image_bytes, actual_model = _generate_with_gemini(prompt)
        width, height = _png_dimensions(image_bytes)
        generated.append({
            "id": asset_id,
            "step_id": step_id,
            "title": title,
            "payload": image_bytes,
            "sha256": hashlib.sha256(image_bytes).hexdigest(),
            "fingerprint": fingerprint,
            "width": width,
            "height": height,
        })

    conn = connect()
    try:
        ensure_blob_table(conn)
        stored = []
        skipped = []
        for item in generated:
            existing = conn.execute(
                "SELECT id, content_fingerprint, status FROM lesson_image_assets WHERE id=%s",
                (item["id"],),
            ).fetchone()
            if existing and not payload.overwrite:
                skipped.append({"step_id": item["step_id"], "status": "already_exists"})
                continue
            object_key = f"generated/{lesson_id}/{item['step_id']}"
            conn.execute(
                """INSERT INTO lesson_image_assets
                   (id, lesson_id, module_key, title, step_ids_json, bucket_name, object_key,
                    content_type, alt_text, status, content_fingerprint, created_at, updated_at)
                   VALUES (%s,%s,%s,%s,%s,%s,%s,'image/png',%s,'pending_review',%s,NOW(),NOW())
                   ON CONFLICT (id) DO UPDATE SET
                     lesson_id=EXCLUDED.lesson_id, module_key=EXCLUDED.module_key,
                     title=EXCLUDED.title, step_ids_json=EXCLUDED.step_ids_json,
                     bucket_name=EXCLUDED.bucket_name, object_key=EXCLUDED.object_key,
                     content_type=EXCLUDED.content_type, alt_text=EXCLUDED.alt_text,
                     status='pending_review', content_fingerprint=EXCLUDED.content_fingerprint,
                     updated_at=NOW()""",
                (item["id"], lesson_id, item["step_id"], item["title"],
                 json.dumps([item["step_id"]]), "postgres-inline-images", object_key,
                 item["title"], item["fingerprint"]),
            )
            conn.execute(
                """INSERT INTO lesson_image_asset_blobs (asset_id,image_bytes,sha256,byte_length)
                   VALUES (%s,%s,%s,%s)
                   ON CONFLICT (asset_id) DO UPDATE SET image_bytes=EXCLUDED.image_bytes,
                     sha256=EXCLUDED.sha256, byte_length=EXCLUDED.byte_length, created_at=NOW()""",
                (item["id"], item["payload"], item["sha256"], len(item["payload"])),
            )
            stored.append({
                "asset_id": item["id"], "step_id": item["step_id"],
                "status": "pending_review", "width": item["width"], "height": item["height"],
                "byte_length": len(item["payload"]), "sha256": item["sha256"],
            })
        conn.commit()
        return {
            "status": "generated_pending_review",
            "lesson_id": lesson_id,
            "model": actual_model,
            "stored_count": len(stored),
            "skipped_count": len(skipped),
            "assets": stored,
            "skipped": skipped,
            "note": "Assets are stored and mapped, but are not visible to learners until reviewed and marked ready.",
        }
    except HTTPException:
        conn.rollback()
        raise
    except Exception as exc:
        conn.rollback()
        raise HTTPException(status_code=500, detail=f"Generated image storage failed ({type(exc).__name__}).") from exc
    finally:
        conn.close()


@router.post("/{asset_id}/approve", dependencies=[Depends(require_image_admin)])
def approve_generated_lesson_image(asset_id: str) -> dict[str, Any]:
    """Make one reviewed image visible to the existing approved-lesson read endpoint."""
    conn = connect()
    try:
        row = conn.execute(
            """SELECT a.id, a.lesson_id, a.status, l.status AS lesson_status
               FROM lesson_image_assets a
               JOIN chapter_lessons l ON l.id=a.lesson_id
               JOIN lesson_image_asset_blobs b ON b.asset_id=a.id
               WHERE a.id=%s""",
            (asset_id,),
        ).fetchone()
        if not row or row["lesson_status"] != "approved" or row["status"] != "pending_review":
            raise HTTPException(status_code=404, detail="Pending image for an approved lesson not found.")
        conn.execute(
            "UPDATE lesson_image_assets SET status='ready', updated_at=NOW() WHERE id=%s",
            (asset_id,),
        )
        conn.commit()
        return {"asset_id": asset_id, "lesson_id": row["lesson_id"], "status": "ready"}
    except HTTPException:
        conn.rollback()
        raise
    except Exception as exc:
        conn.rollback()
        raise HTTPException(status_code=500, detail=f"Image approval failed ({type(exc).__name__}).") from exc
    finally:
        conn.close()
